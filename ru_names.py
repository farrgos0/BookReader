CASES = ("nom", "gen", "dat", "acc", "ins", "prep")
_IRREG_FIRST = {"Лев": ("Лев", "Льва", "Льву", "Льва", "Львом", "Льве"),
                "Павел": ("Павел", "Павла", "Павлу", "Павла", "Павлом", "Павле")}


def _masc_first(w):
    if w in _IRREG_FIRST:
        return _IRREG_FIRST[w]
    if w.endswith(("й", "ь")):
        s = w[:-1]
        return (w, s + "я", s + "ю", s + "я", s + "ем", s + "е")
    return (w, w + "а", w + "у", w + "а", w + "ом", w + "е")


def _masc_patr(w):
    return (w, w + "а", w + "у", w + "а", w + "ем", w + "е")


def _fem(w):  # Анна, Марина, Андреевна
    s = w[:-1]
    gen = s + ("и" if s[-1] in "гкхжшщч" else "ы")
    return (w, gen, s + "е", s + "у", s + ("ей" if s[-1] in "жшщчц" else "ой"), s + "е")


def _surname_forms(sur):
    """Формы фамилии по падежам; у мужских на -ов/-ин ед. творительный — «-ым»."""
    if sur.endswith(("ова", "ева", "ина", "ына")):          # Ахматова, Цветаева
        s = sur[:-1]
        return (sur, s + "ой", s + "ой", s + "у", s + "ой", s + "ой"), "f"
    if sur.endswith(("ский", "цкий", "кий")):               # Достоевский, Горький
        s = sur[:-2]
        return (sur, s + "ого", s + "ому", s + "ого", s + "им", s + "ом"), "m"
    if sur.endswith("ой"):                                  # Толстой
        s = sur[:-2]
        return (sur, s + "ого", s + "ому", s + "ого", s + "ым", s + "ом"), "m"
    if sur.endswith(("ов", "ев", "ёв", "ин", "ын")):         # Пушкин, Чехов
        return (sur, sur + "а", sur + "у", sur + "а", sur + "ым", sur + "е"), "m"
    if sur.endswith("ь"):                                   # Гоголь
        s = sur[:-1]
        return (sur, s + "я", s + "ю", s + "я", s + "ем", s + "е"), "m"
    if sur.endswith(("о", "е", "и", "у", "ю")) or "-" in sur:  # Зощенко, Короленко — не склоняются
        return (sur,) * 6, "m"
    return (sur, sur + "а", sur + "у", sur + "а", sur + "ом", sur + "е"), "m"


def _build():
    forms = {}
    for sur, writers in CLASSICS.items():
        sforms, g = _surname_forms(sur)
        for case, f in zip(CASES, sforms):
            forms.setdefault(f, [])
            i = CASES.index(case)
            for ini, full in writers:
                parts = full.split()
                if g == "f":
                    named = [_fem(p)[i] for p in parts]
                else:
                    named = [_masc_first(parts[0])[i]] + [_masc_patr(p)[i] for p in parts[1:]]
                forms[f].append((ini, case, " ".join(named)))
    return forms


