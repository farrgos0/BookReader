_INI = r"(?:[А-ЯЁ]\.[ \u00a0]?){1,2}"
_SUR = r"[А-ЯЁ][а-яё]+(?:-[А-ЯЁ][а-яё]+)?"
_RE_BEFORE = re.compile(rf"(?<![\w.])({_INI})[ \u00a0]?({_SUR})(?![\w])")    # А.С. Пушкин, А. С. Пушкин, А.С.Пушкин
_RE_AFTER = re.compile(rf"(?<![\w.])({_SUR})[ \u00a0]+({_INI})(?![\w])")      # Пушкин А.С.


def _letters(ini):
    return [c for c in ini if c.isalpha()]


def _spell(ini):
    return " ".join(LETTERS.get(c, c) for c in _letters(ini))


def _expand(ini_raw, sur, prep):
    """Полное имя классика в падеже фамилии (при нескольких падежах — по предлогу) или None."""
    ini = "".join(_letters(ini_raw))
    found = [(case, full) for want, case, full in FORMS.get(sur, []) if want == ini]
    if not found:
        return None
    want_case = PREP_CASE.get(prep)
    for case, full in found:
        if case == want_case:
            return full
    return found[0][1]


def _prev_word(text, pos):
    m = re.search(r"([\w-]+)[\s\u00a0]*$", text[:pos])
    return m.group(1).lower() if m else ""


def _sentence_start(text, pos):
    return not re.search(r"[\w]", re.split(r"[.!?…]\s", text[:pos])[-1])


def initials(text):
    def end(m, src):
        # точка последнего инициала в конце предложения — она же конец предложения: «…Пушкин А.С. Потом…»
        rest = src[m.end():]
        return "." if m.group(0).rstrip().endswith(".") and (not rest.strip() or re.match(r"\s*[А-ЯЁA-Z«\"]", rest)) else ""

    # 1) классики — в обоих порядках, полным именем
    def classic_after(m):
        full = _expand(m.group(2), m.group(1), _prev_word(text, m.start()))
        return f"{full} {m.group(1)}" + end(m, text) if full else m.group(0)
    text = _RE_AFTER.sub(classic_after, text)

    def classic_before(m):
        full = _expand(m.group(1), m.group(2), _prev_word(text, m.start()))
        return f"{full} {m.group(2)}" if full else m.group(0)
    text = _RE_BEFORE.sub(classic_before, text)

    # 2) остальные — инициалы названиями букв. «Иванов И.И. пришёл» — после фамилии; «И.И. Иванов» — перед.
    def other_after(m):
        if _sentence_start(text, m.start()) and _RE_BEFORE.match(text, m.start(2)):
            return m.group(0)   # «Писатель А.С. Иванов»: «Писатель» — первое слово предложения, не фамилия
        return f"{m.group(1)} {_spell(m.group(2))}" + end(m, text)
    text = _RE_AFTER.sub(other_after, text)

    def other_before(m):
        if m.group(2).lower() in NOT_SURNAMES:
            return m.group(0)   # «Ответил Б. Он ушёл.» — «Он» начинает новое предложение, это не фамилия
        return f"{_spell(m.group(1))} {m.group(2)}"
    return _RE_BEFORE.sub(other_before, text)
