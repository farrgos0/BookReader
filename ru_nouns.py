def analyses(word):
    """Все разборы формы: [(слово, род, номер после слова, падеж, число)] или []."""
    return FORMS.get(word.lower().replace("ё", "е"), []) or FORMS.get(word.lower(), [])


def form_of(lemma, case, number="sg"):
    gender, kind, _ = _LEMMAS[lemma]
    sg, pl = _decline(lemma, kind)
    return (sg if number == "sg" else pl)[CASES.index(case)]


def pick(an, prep=None, number="sg"):
    """Из разборов — один: нужного числа, падеж по предлогу, если он есть."""
    cand = [a for a in an if a[4] == number]
    if not cand:
        return None
    want = PREP_CASE.get(prep or "")
    for a in cand:
        if want and a[3] == want:
            return a
    # «на» и «в» с винительным: «на 5 уровень» — но предложный важнее, его уже проверили
    if prep in ("в", "на", "за", "про", "через") and any(a[3] == "acc" for a in cand):
        return next(a for a in cand if a[3] == "acc")
    for c in ("nom", "gen", "prep", "dat", "ins", "acc"):
        for a in cand:
            if a[3] == c:
                return a
    return cand[0]


def count_agrees(n, case, number):
    """Согласуется ли форма слова с числом как с количеством: «2 главы», «5 глав», «в 2 главах»."""
    last2, last = n % 100, n % 10
    one = last == 1 and last2 != 11
    few = 2 <= last <= 4 and not 12 <= last2 <= 14
    if case in ("nom", "acc"):                       # «1 глава», «21 день»
        return one and number == "sg"
    if case == "gen" and number == "sg" and few:     # «2 главы», «3 дня»
        return True
    if case == "gen" and number == "pl" and not one:  # «5 глав», «до 5 глав»
        return True
    # косвенные падежи: «в одной главе», «в 2 главах», «к 3 урокам»
    return (number == "sg") == one
